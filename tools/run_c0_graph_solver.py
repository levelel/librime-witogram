def load_jsonl(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for raw_line in handle:
            line = raw_line.strip()
            if not line:
                continue
            payload = json.loads(line)
            if isinstance(payload, dict):
                records.append(payload)
    return records


def iter_jsonl_records(path: Path) -> Any:
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for raw_line in handle:
            line = raw_line.strip()
            if not line:
                continue
            json_start = line.find("{")
            if json_start > 0:
                line = line[json_start:]
            try:
                payload = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(payload, dict):
                yield payload


def utf8_char_count(text: str) -> int:
    return len(text)


def build_context_suffix(previous_suffix: str, word: str, token_limit: int) -> str:
    if token_limit <= 0:
        return ""
    tokens = list(previous_suffix) + list(word)
    if len(tokens) > token_limit:
        tokens = tokens[-token_limit:]
    return "".join(tokens)


def length_class(char_count: int) -> int:
    if char_count <= 1:
        return 1
    if char_count == 2:
        return 2
    return 3


def update_recent_len_signature(previous_signature: str, current_class: int) -> str:
    parts = [part for part in previous_signature.split("-") if part]
    parts.append(str(current_class))
    return "-".join(parts[-2:])


def score_word_edge(
    candidate: dict[str, Any],
    edge_risk: float,
    edge_spelling_class: int,
    vertex_risk: float,
    weights: SolverWeights,
) -> tuple[float, str]:
    text = str(candidate.get("text", ""))
    char_count = max(1, utf8_char_count(text))
    dict_weight = float(candidate.get("weight", 0.0))
    score = dict_weight * weights.dict_weight
    score -= edge_risk * weights.edge_risk_weight
    score -= vertex_risk * weights.vertex_risk_weight
    if edge_spelling_class >= 4:
        score -= weights.ambiguous_edge_penalty
    if char_count == 1:
        score -= weights.single_char_penalty
    else:
        score += weights.multi_char_bonus * float(char_count - 1)
    debug = (
        f"text={text} dict={dict_weight:.3f} edge_risk={edge_risk:.3f} "
        f"vertex_risk={vertex_risk:.3f} class={edge_spelling_class} "
        f"chars={char_count} score={score:.3f}"
    )
    return score, debug


def make_transition_key(context_suffix: str, word: str, is_rear: bool) -> tuple[str, str, bool]:
    return (context_suffix, word, is_rear)


def score_transition_context(
    transition_record: dict[str, Any] | None,
    weights: SolverWeights,
) -> tuple[float, str]:
    if not transition_record:
        return 0.0, "ctx=missing"
    if not bool(transition_record.get("has_lm_features", False)):
        return 0.0, "ctx=none"
    total_log10 = float(transition_record.get("total_log10", 0.0) or 0.0)
    avg_log10 = float(transition_record.get("avg_log10", 0.0) or 0.0)
    oov_token_count = int(transition_record.get("oov_token_count", 0) or 0)
    used_char_fallback = bool(transition_record.get("used_char_fallback", False))
    matched_whole_word = bool(transition_record.get("matched_whole_word", False))
    score = total_log10 * weights.ctx_total_weight
    score += avg_log10 * weights.ctx_avg_weight
    score -= float(oov_token_count) * weights.ctx_oov_penalty
    if used_char_fallback:
        score -= weights.ctx_fallback_penalty
    if matched_whole_word:
        score += weights.ctx_whole_word_bonus
    debug = (
        f"ctx_total={total_log10:.3f} ctx_avg={avg_log10:.3f} "
        f"ctx_oov={oov_token_count} ctx_fb={int(used_char_fallback)} "
        f"ctx_whole={int(matched_whole_word)} ctx_score={score:.3f}"
    )
    return score, debug


def build_transition_lm_index(
    record: dict[str, Any],
) -> tuple[dict[tuple[str, str, bool], dict[str, Any]], int]:
    context_token_limit = int(record.get("context_token_limit", 0) or 0)
    transition_lm_index: dict[tuple[str, str, bool], dict[str, Any]] = {}
    for transition in record.get("transition_lm_features", []):
        if not isinstance(transition, dict):
            continue
        key = make_transition_key(
            str(transition.get("context_suffix", "")),
            str(transition.get("word", "")),
            bool(transition.get("is_rear", False)),
        )
        transition_lm_index[key] = transition
    return transition_lm_index, context_token_limit


def build_word_edges_by_start(record: dict[str, Any]) -> dict[int, list[dict[str, Any]]]:
    word_edges_by_start: dict[int, list[dict[str, Any]]] = {}
    for edge in record.get("word_edges", []):
        if not isinstance(edge, dict):
            continue
        word_edges_by_start.setdefault(int(edge.get("start", 0) or 0), []).append(edge)
    return word_edges_by_start


def score_transition_with_presence(
    transition_lm_index: dict[tuple[str, str, bool], dict[str, Any]],
    context_suffix: str,
    word: str,
    is_rear: bool,
    weights: SolverWeights,
) -> tuple[float, str, bool]:
    record = transition_lm_index.get(make_transition_key(context_suffix, word, is_rear))
    score, debug = score_transition_context(record, weights)
    has_features = bool(record and record.get("has_lm_features", False))
    return score, debug, has_features


def apply_local_context_substitutions(
    state: PathState,
    word_edges_by_start: dict[int, list[dict[str, Any]]],
    transition_lm_index: dict[tuple[str, str, bool], dict[str, Any]],
    context_token_limit: int,
    weights: SolverWeights,
    require_nonnegative_base_diff: bool = False,
) -> PathState:
    if not state.segments:
        return state
    updated_words: list[str] = []
    updated_segments: list[PathSegment] = []
    debug_parts = list(state.debug_parts)
    total_gain = 0.0
    context_suffix = ""
    segment_count = len(state.segments)
    for index, segment in enumerate(state.segments):
        edge = None
        for candidate_edge in word_edges_by_start.get(segment.start, []):
            if int(candidate_edge.get("end", segment.start) or segment.start) == segment.end:
                edge = candidate_edge
                break
        if edge is None:
            updated_words.append(segment.word)
            updated_segments.append(segment)
            context_suffix = build_context_suffix(
                context_suffix, segment.word, context_token_limit
            )
            continue
        chosen_candidate = {"text": segment.word, "weight": segment.dict_weight}
        chosen_base, _ = score_word_edge(
            chosen_candidate,
            segment.edge_risk,
            segment.edge_spelling_class,
            segment.vertex_risk,
            weights,
        )
        chosen_curr_ctx, _, chosen_curr_has = score_transition_with_presence(
            transition_lm_index,
            context_suffix,
            segment.word,
            segment.is_rear,
            weights,
        )
        next_word = state.segments[index + 1].word if index + 1 < segment_count else ""
        next_is_rear = bool(index + 1 == segment_count - 1)
        chosen_next_suffix = build_context_suffix(
            context_suffix, segment.word, context_token_limit
        )
        chosen_next_ctx = 0.0
        chosen_next_has = False
        if next_word:
            chosen_next_ctx, _, chosen_next_has = score_transition_with_presence(
                transition_lm_index,
                chosen_next_suffix,
                next_word,
                next_is_rear,
                weights,
            )
        chosen_total_ctx = chosen_curr_ctx + chosen_next_ctx
        chosen_has_signal = chosen_curr_has or chosen_next_has
        best_word = segment.word
        best_dict_weight = segment.dict_weight
        best_gain = 0.0
        best_debug = "local_ctx keep=no_better_alt"
        candidates = edge.get("candidates", [])
        if isinstance(candidates, list):
            chosen_char_count = utf8_char_count(segment.word)
            for candidate in candidates:
                if not isinstance(candidate, dict):
                    continue
                alt_word = str(candidate.get("text", ""))
                if not alt_word or alt_word == segment.word:
                    continue
                if utf8_char_count(alt_word) != chosen_char_count:
                    continue
                alt_base, _ = score_word_edge(
                    candidate,
                    segment.edge_risk,
                    segment.edge_spelling_class,
                    segment.vertex_risk,
                    weights,
                )
                if require_nonnegative_base_diff and alt_base < chosen_base:
                    continue
                if alt_base < chosen_base - weights.ctx_local_base_margin:
                    continue
                alt_curr_ctx, _, alt_curr_has = score_transition_with_presence(
                    transition_lm_index,
                    context_suffix,
                    alt_word,
                    segment.is_rear,
                    weights,
                )
                alt_next_suffix = build_context_suffix(
                    context_suffix, alt_word, context_token_limit
                )
                alt_next_ctx = 0.0
                alt_next_has = False
                if next_word:
                    alt_next_ctx, _, alt_next_has = score_transition_with_presence(
                        transition_lm_index,
                        alt_next_suffix,
                        next_word,
                        next_is_rear,
                        weights,
                    )
                alt_has_signal = alt_curr_has or alt_next_has
                if not alt_has_signal and not chosen_has_signal:
                    continue
                base_diff = alt_base - chosen_base
                ctx_diff = (alt_curr_ctx + alt_next_ctx) - chosen_total_ctx
                gain = base_diff + ctx_diff * weights.ctx_local_scale
                if gain > best_gain and gain > weights.ctx_local_gain_threshold:
                    best_gain = gain
                    best_word = alt_word
                    best_dict_weight = float(candidate.get("weight", 0.0) or 0.0)
                    best_debug = (
                        f"local_ctx replace start={segment.start} end={segment.end} "
                        f"{segment.word}->{alt_word} base_diff={base_diff:.3f} "
                        f"ctx_diff={ctx_diff:.3f} scale={weights.ctx_local_scale:.3f} "
                        f"gain={gain:.3f}"
                    )
        chosen_word = best_word
        chosen_dict_weight = best_dict_weight
        total_gain += best_gain
        debug_parts.append(best_debug)
        updated_words.append(chosen_word)
        updated_segments.append(
            PathSegment(
                start=segment.start,
                end=segment.end,
                word=chosen_word,
                dict_weight=chosen_dict_weight,
                edge_risk=segment.edge_risk,
                edge_spelling_class=segment.edge_spelling_class,
                vertex_risk=segment.vertex_risk,
                is_rear=segment.is_rear,
            )
        )
        context_suffix = build_context_suffix(context_suffix, chosen_word, context_token_limit)
    return PathState(
        score=state.score + total_gain,
        text="".join(updated_words),
        words=updated_words,
        debug_parts=debug_parts,
        segments=updated_segments,
        context_suffix=context_suffix,
        last_word_len_class=state.last_word_len_class,
        trailing_single_char_run=state.trailing_single_char_run,
        recent_len_signature=state.recent_len_signature,
    )


def compute_path_context_rerank(
    state: PathState,
    transition_lm_index: dict[tuple[str, str, bool], dict[str, Any]],
    context_token_limit: int,
    weights: SolverWeights,
) -> tuple[float, list[str], str]:
    context_suffix = ""
    total_ctx_score = 0.0
    debug_parts: list[str] = []
    word_count = len(state.words)
    for index, word in enumerate(state.words):
        is_rear = index == word_count - 1
        transition_key = make_transition_key(context_suffix, word, is_rear)
        ctx_score, ctx_debug = score_transition_context(
            transition_lm_index.get(transition_key), weights
        )
        total_ctx_score += ctx_score
        debug_parts.append(
            f"rerank[{index}] word={word} suffix={context_suffix or '<root>'} {ctx_debug}"
        )
        context_suffix = build_context_suffix(context_suffix, word, context_token_limit)
    return total_ctx_score, debug_parts, context_suffix


def score_word_edge_c01(
    candidate: dict[str, Any],
    edge_risk: float,
    edge_spelling_class: int,
    vertex_risk: float,
    weights: SolverWeights,
    state: PathState,
) -> tuple[float, str, int, int, str]:
    score, debug = score_word_edge(
        candidate, edge_risk, edge_spelling_class, vertex_risk, weights
    )
    text = str(candidate.get("text", ""))
    char_count = max(1, utf8_char_count(text))
    current_len_class = length_class(char_count)
    next_trailing_single_char_run = (
        min(3, state.trailing_single_char_run + 1) if char_count == 1 else 0
    )
    recent_signature = update_recent_len_signature(
        state.recent_len_signature, current_len_class
    )

    state_adjustment = 0.0
    if char_count == 1 and state.last_word_len_class >= 2:
        state_adjustment -= 0.45 + 0.25 * float(state.trailing_single_char_run)
    if char_count == 1 and state.trailing_single_char_run >= 1:
        state_adjustment -= 0.35 * float(state.trailing_single_char_run)
    if char_count >= 2 and state.trailing_single_char_run >= 2:
        state_adjustment += 0.30
    if recent_signature == "1-1":
        state_adjustment -= 0.30
    elif recent_signature == "3-1":
        state_adjustment -= 0.20
    elif recent_signature == "2-2":
        state_adjustment += 0.10

    score += state_adjustment
    debug += (
        f" state_adj={state_adjustment:.3f} last_len={state.last_word_len_class} "
        f"trail1={state.trailing_single_char_run} recent={state.recent_len_signature or 'root'}"
    )
    return (
        score,
        debug,
        current_len_class,
        next_trailing_single_char_run,
        recent_signature,
    )


def solve_graph_record(
    record: dict[str, Any], weights: SolverWeights, top_k: int
) -> list[PathState]:
    interpreted_length = int(record.get("interpreted_length", 0) or 0)
    vertex_risks = {
        int(vertex.get("pos", 0)): float(vertex.get("risk", 0.0) or 0.0)
        for vertex in record.get("vertices", [])
        if isinstance(vertex, dict)
    }
    word_edges_by_start = build_word_edges_by_start(record)

    best_states: dict[int, list[PathState]] = {
        0: [PathState(score=0.0, text="", words=[], debug_parts=[], context_suffix="")]
    }
    for pos in range(interpreted_length + 1):
        states = best_states.get(pos) or []
        if not states:
            continue
        for edge in word_edges_by_start.get(pos, []):
            end = int(edge.get("end", pos) or pos)
            edge_risk = float(edge.get("edge_risk", 0.0) or 0.0)
            edge_spelling_class = int(edge.get("edge_spelling_class", 0) or 0)
            vertex_risk = vertex_risks.get(end, 0.0)
            candidates = edge.get("candidates", [])
            if not isinstance(candidates, list):
                continue
            for state in states:
                for candidate in candidates:
                    if not isinstance(candidate, dict):
                        continue
                    delta_score, debug = score_word_edge(
                        candidate, edge_risk, edge_spelling_class, vertex_risk, weights
                    )
                    word = str(candidate.get("text", ""))
                    next_state = PathState(
                        score=state.score + delta_score,
                        text=state.text + word,
                        words=state.words + [word],
                        debug_parts=state.debug_parts + [f"{pos}->{end} {debug}"],
                        segments=state.segments
                        + [
                            PathSegment(
                                start=pos,
                                end=end,
                                word=word,
                                dict_weight=float(candidate.get("weight", 0.0) or 0.0),
                                edge_risk=edge_risk,
                                edge_spelling_class=edge_spelling_class,
                                vertex_risk=vertex_risk,
                                is_rear=(end == interpreted_length),
                            )
                        ],
                        context_suffix="",
                    )
                    bucket = best_states.setdefault(end, [])
                    bucket.append(next_state)
                    bucket.sort(key=lambda item: item.score, reverse=True)
                    del bucket[top_k:]
    finals = best_states.get(interpreted_length, [])
    finals.sort(key=lambda item: item.score, reverse=True)
    return finals


def solve_graph_record_c0_ctx(
    record: dict[str, Any], weights: SolverWeights, top_k: int
) -> list[PathState]:
    interpreted_length = int(record.get("interpreted_length", 0) or 0)
    transition_lm_index, context_token_limit = build_transition_lm_index(record)
    vertex_risks = {
        int(vertex.get("pos", 0)): float(vertex.get("risk", 0.0) or 0.0)
        for vertex in record.get("vertices", [])
        if isinstance(vertex, dict)
    }
    word_edges_by_start: dict[int, list[dict[str, Any]]] = {}
    for edge in record.get("word_edges", []):
        if not isinstance(edge, dict):
            continue
        word_edges_by_start.setdefault(int(edge.get("start", 0) or 0), []).append(edge)

    best_states: dict[int, list[PathState]] = {
        0: [PathState(score=0.0, text="", words=[], debug_parts=[], context_suffix="")]
    }
    for pos in range(interpreted_length + 1):
        states = best_states.get(pos) or []
        if not states:
            continue
        for edge in word_edges_by_start.get(pos, []):
            end = int(edge.get("end", pos) or pos)
            edge_risk = float(edge.get("edge_risk", 0.0) or 0.0)
            edge_spelling_class = int(edge.get("edge_spelling_class", 0) or 0)
            vertex_risk = vertex_risks.get(end, 0.0)
            is_rear = end == interpreted_length
            candidates = edge.get("candidates", [])
            if not isinstance(candidates, list):
                continue
            for state in states:
                for candidate in candidates:
                    if not isinstance(candidate, dict):
                        continue
                    delta_score, debug = score_word_edge(
                        candidate, edge_risk, edge_spelling_class, vertex_risk, weights
                    )
                    word = str(candidate.get("text", ""))
                    transition_key = make_transition_key(
                        state.context_suffix, word, is_rear
                    )
                    ctx_score, ctx_debug = score_transition_context(
                        transition_lm_index.get(transition_key), weights
                    )
                    next_context_suffix = build_context_suffix(
                        state.context_suffix, word, context_token_limit
                    )
                    next_state = PathState(
                        score=state.score + delta_score + ctx_score,
                        text=state.text + word,
                        words=state.words + [word],
                        debug_parts=state.debug_parts
                        + [f"{pos}->{end} {debug} {ctx_debug}"],
                        context_suffix=next_context_suffix,
                    )
                    bucket = best_states.setdefault(end, [])
                    bucket.append(next_state)
                    bucket.sort(key=lambda item: item.score, reverse=True)
                    del bucket[top_k:]
    finals = best_states.get(interpreted_length, [])
    finals.sort(key=lambda item: item.score, reverse=True)
    return finals


def solve_graph_record_c0_ctx_rerank(
    record: dict[str, Any], weights: SolverWeights, top_k: int
) -> list[PathState]:
    expanded_top_k = max(top_k * 4, 16)
    base_results = solve_graph_record(record, weights, expanded_top_k)
    if not base_results:
        return []
    transition_lm_index, context_token_limit = build_transition_lm_index(record)
    best_base_score = base_results[0].score
    reranked_results: list[PathState] = []
    for state in base_results:
        ctx_total, ctx_debug_parts, final_context_suffix = compute_path_context_rerank(
            state, transition_lm_index, context_token_limit, weights
        )
        within_margin = state.score >= best_base_score - weights.ctx_rerank_margin
        rerank_bonus = (
            ctx_total * weights.ctx_rerank_scale if within_margin else 0.0
        )
        rerank_note = (
            f"rerank base={state.score:.3f} ctx_total={ctx_total:.3f} "
            f"scale={weights.ctx_rerank_scale:.3f} "
            f"margin={weights.ctx_rerank_margin:.3f} "
            f"applied={int(within_margin)} bonus={rerank_bonus:.3f} "
            f"final={state.score + rerank_bonus:.3f}"
        )
        reranked_results.append(
            PathState(
                score=state.score + rerank_bonus,
                text=state.text,
                words=state.words,
                debug_parts=state.debug_parts + [rerank_note] + ctx_debug_parts,
                context_suffix=final_context_suffix,
                last_word_len_class=state.last_word_len_class,
                trailing_single_char_run=state.trailing_single_char_run,
                recent_len_signature=state.recent_len_signature,
            )
        )
    reranked_results.sort(key=lambda item: item.score, reverse=True)
    return reranked_results[: max(top_k * 3, 12)]


def solve_graph_record_c0_ctx_local(
    record: dict[str, Any], weights: SolverWeights, top_k: int
) -> list[PathState]:
    base_results = solve_graph_record(record, weights, max(top_k * 4, 16))
    if not base_results:
        return []
    transition_lm_index, context_token_limit = build_transition_lm_index(record)
    word_edges_by_start = build_word_edges_by_start(record)
    localized_results = [
        apply_local_context_substitutions(
            state,
            word_edges_by_start,
            transition_lm_index,
            context_token_limit,
            weights,
        )
        for state in base_results
    ]
    localized_results.sort(key=lambda item: item.score, reverse=True)
    return localized_results[: max(top_k * 3, 12)]


def solve_graph_record_c0_ctx_local_top1(
    record: dict[str, Any], weights: SolverWeights, top_k: int
) -> list[PathState]:
    base_results = solve_graph_record(record, weights, max(top_k * 4, 16))
    if not base_results:
        return []
    transition_lm_index, context_token_limit = build_transition_lm_index(record)
    word_edges_by_start = build_word_edges_by_start(record)
    anchor = base_results[0]
    localized_anchor = apply_local_context_substitutions(
        anchor,
        word_edges_by_start,
        transition_lm_index,
        context_token_limit,
        weights,
        require_nonnegative_base_diff=True,
    )
    combined_results: list[PathState] = [anchor]
    if (
        localized_anchor.text != anchor.text
        or localized_anchor.score != anchor.score
        or localized_anchor.debug_parts != anchor.debug_parts
    ):
        combined_results.append(localized_anchor)
    combined_results.extend(base_results[1 : max(top_k * 3, 12)])
    combined_results.sort(key=lambda item: item.score, reverse=True)
    return combined_results[: max(top_k * 3, 12)]


def solve_graph_record_c01(
    record: dict[str, Any], weights: SolverWeights, top_k: int
) -> list[PathState]:
    interpreted_length = int(record.get("interpreted_length", 0) or 0)
    vertex_risks = {
        int(vertex.get("pos", 0)): float(vertex.get("risk", 0.0) or 0.0)
        for vertex in record.get("vertices", [])
        if isinstance(vertex, dict)
    }
    word_edges_by_start: dict[int, list[dict[str, Any]]] = {}
    for edge in record.get("word_edges", []):
        if not isinstance(edge, dict):
            continue
        word_edges_by_start.setdefault(int(edge.get("start", 0) or 0), []).append(edge)

    best_states: dict[int, dict[str, list[PathState]]] = {
        0: {
            "root": [
                PathState(
                    score=0.0,
                    text="",
                    words=[],
                    debug_parts=[],
                    last_word_len_class=0,
                    trailing_single_char_run=0,
                    recent_len_signature="",
                )
            ]
        }
    }
    for pos in range(interpreted_length + 1):
        state_groups = best_states.get(pos) or {}
        if not state_groups:
            continue
        flat_states: list[PathState] = []
        for group_states in state_groups.values():
            flat_states.extend(group_states)
        for edge in word_edges_by_start.get(pos, []):
            end = int(edge.get("end", pos) or pos)
            edge_risk = float(edge.get("edge_risk", 0.0) or 0.0)
            edge_spelling_class = int(edge.get("edge_spelling_class", 0) or 0)
            vertex_risk = vertex_risks.get(end, 0.0)
            candidates = edge.get("candidates", [])
            if not isinstance(candidates, list):
                continue
            for state in flat_states:
                for candidate in candidates:
                    if not isinstance(candidate, dict):
                        continue
                    (
                        delta_score,
                        debug,
                        current_len_class,
                        next_trailing_single_char_run,
                        recent_signature,
                    ) = score_word_edge_c01(
                        candidate,
                        edge_risk,
                        edge_spelling_class,
                        vertex_risk,
                        weights,
                        state,
                    )
                    word = str(candidate.get("text", ""))
                    next_state = PathState(
                        score=state.score + delta_score,
                        text=state.text + word,
                        words=state.words + [word],
                        debug_parts=state.debug_parts + [f"{pos}->{end} {debug}"],
                        last_word_len_class=current_len_class,
                        trailing_single_char_run=next_trailing_single_char_run,
                        recent_len_signature=recent_signature,
                    )
                    state_key = (
                        f"{current_len_class}|{next_trailing_single_char_run}|"
                        f"{recent_signature or 'root'}"
                    )
                    end_groups = best_states.setdefault(end, {})
                    bucket = end_groups.setdefault(state_key, [])
                    bucket.append(next_state)
                    bucket.sort(key=lambda item: item.score, reverse=True)
                    del bucket[top_k:]
        if pos in best_states:
            end_groups = best_states[pos]
            trimmed_groups: dict[str, list[PathState]] = {}
            for state_key, bucket in end_groups.items():
                trimmed_groups[state_key] = bucket[:top_k]
            best_states[pos] = trimmed_groups

    finals: list[PathState] = []
    for bucket in (best_states.get(interpreted_length) or {}).values():
        finals.extend(bucket)
    finals.sort(key=lambda item: item.score, reverse=True)
    return finals[: max(top_k * 3, 12)]


