def build_reference_index(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    ordered = [record for record in records if isinstance(record, dict)]
    ordered.sort(key=lambda item: int(item.get("step_index", 0) or 0))
    return ordered


def build_graph_index(records: list[dict[str, Any]]) -> dict[tuple[str, str], dict[str, Any]]:
    index: dict[tuple[str, str], dict[str, Any]] = {}
    for record in records:
        key = (str(record.get("input", "")), str(record.get("preceding_text", "")))
        index[key] = record
    return index


def build_graph_input_index(records: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    index: dict[str, dict[str, Any]] = {}
    for record in records:
        index[str(record.get("input", ""))] = record
    return index


def build_graph_indices_for_inputs(
    graph_path: Path, target_inputs: set[str]
) -> tuple[
    dict[tuple[str, str], dict[str, Any]],
    dict[str, dict[str, Any]],
    int,
    int | None,
    int | None,
]:
    graph_index: dict[tuple[str, str], dict[str, Any]] = {}
    graph_input_index: dict[str, dict[str, Any]] = {}
    graph_record_count = 0
    first_timestamp_ms: int | None = None
    last_timestamp_ms: int | None = None
    for record in iter_jsonl_records(graph_path):
        graph_record_count += 1
        timestamp = record.get("timestamp_ms")
        if isinstance(timestamp, (int, float)):
            ts_value = int(timestamp)
            if first_timestamp_ms is None or ts_value < first_timestamp_ms:
                first_timestamp_ms = ts_value
            if last_timestamp_ms is None or ts_value > last_timestamp_ms:
                last_timestamp_ms = ts_value
        record_input = str(record.get("input", ""))
        if record_input not in target_inputs:
            continue
        record_preceding = str(record.get("preceding_text", ""))
        graph_index[(record_input, record_preceding)] = record
        graph_input_index[record_input] = record
    return (
        graph_index,
        graph_input_index,
        graph_record_count,
        first_timestamp_ms,
        last_timestamp_ms,
    )


def file_metadata(path: Path) -> dict[str, Any]:
    stat = path.stat()
    return {
        "path": str(path),
        "size_bytes": stat.st_size,
        "last_modified_iso": datetime.fromtimestamp(stat.st_mtime).isoformat(),
    }


def extract_timestamp_bounds(records: list[dict[str, Any]]) -> tuple[int | None, int | None]:
    timestamps = [
        int(record.get("timestamp_ms", 0) or 0)
        for record in records
        if isinstance(record.get("timestamp_ms"), (int, float))
    ]
    if not timestamps:
        return None, None
    return min(timestamps), max(timestamps)


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


def write_markdown(path: Path, summary: dict[str, Any], mismatches: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# C0 Graph Solver Summary",
        "",
        "## Metrics",
        "",
        f"- Evaluated cases: {summary['evaluated_case_count']}",
        f"- Missing graph cases: {summary['missing_graph_case_count']}",
        f"- Top-1 hits: {summary['top1_hit_count']}",
        f"- Top-3 hits: {summary['top3_hit_count']}",
        f"- Top-1 accuracy: {summary['top1_accuracy']:.6f}",
        f"- Top-3 accuracy: {summary['top3_accuracy']:.6f}",
        f"- Match by preceding_text: {summary['match_by_preceding_count']}",
        f"- Match by snapshot_preceding_text: {summary['match_by_snapshot_preceding_count']}",
        f"- Match by input only: {summary['match_by_input_only_count']}",
        "",
        "## Top-1 Mismatches",
        "",
    ]
    if not mismatches:
        lines.append("- None")
    else:
        for item in mismatches[:30]:
            lines.append(
                f"- {item['input']} -> top1={item['top1_text']} | expected={item['expected_text']}"
            )
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    args = parse_args()
    graph_path = Path(args.graph).expanduser().resolve()
    reference_path = Path(args.reference).expanduser().resolve()
    output_json = Path(args.output_json).expanduser().resolve()
    output_md = Path(args.output_md).expanduser().resolve()

    if not graph_path.is_file():
        raise SystemExit(f"Graph snapshot not found: {graph_path}")
    if not reference_path.is_file():
        raise SystemExit(f"Reference file not found: {reference_path}")

    weights = SolverWeights()
    references = build_reference_index(load_jsonl(reference_path))
    if args.input:
        references = [record for record in references if record.get("input") == args.input]
    if args.limit is not None:
        references = references[: args.limit]
    target_inputs = {str(reference.get("input", "")) for reference in references}
    (
        graph_index,
        graph_input_index,
        graph_record_count,
        graph_first_ts,
        graph_last_ts,
    ) = build_graph_indices_for_inputs(graph_path, target_inputs)

    summary: dict[str, Any] = {
        "graph": str(graph_path),
        "reference": str(reference_path),
        "solver": args.solver,
        "graph_record_count": graph_record_count,
        "reference_case_count": len(references),
        "graph_file": file_metadata(graph_path),
        "reference_file": file_metadata(reference_path),
        "evaluated_case_count": 0,
        "missing_graph_case_count": 0,
        "top1_hit_count": 0,
        "top3_hit_count": 0,
        "top1_accuracy": 0.0,
        "top3_accuracy": 0.0,
        "match_by_preceding_count": 0,
        "match_by_snapshot_preceding_count": 0,
        "match_by_input_only_count": 0,
        "weights": weights.__dict__,
        "warnings": [],
    }
    summary["graph_first_timestamp_ms"] = graph_first_ts
    summary["graph_last_timestamp_ms"] = graph_last_ts
    details: list[dict[str, Any]] = []
    top1_hits = 0
    top3_hits = 0

    for reference in references:
        key = (str(reference.get("input", "")), str(reference.get("preceding_text", "")))
        match_strategy = "preceding_text"
        graph_record = graph_index.get(key)
        if graph_record is None:
            fallback_key = (
                str(reference.get("input", "")),
                str(reference.get("snapshot_preceding_text", "")),
            )
            graph_record = graph_index.get(fallback_key)
            if graph_record is not None:
                match_strategy = "snapshot_preceding_text"
        if graph_record is None:
            graph_record = graph_input_index.get(str(reference.get("input", "")))
            if graph_record is not None:
                match_strategy = "input_only"
        if graph_record is None:
            summary["missing_graph_case_count"] += 1
            continue
        summary["evaluated_case_count"] += 1
        if match_strategy == "preceding_text":
            summary["match_by_preceding_count"] += 1
        elif match_strategy == "snapshot_preceding_text":
            summary["match_by_snapshot_preceding_count"] += 1
        else:
            summary["match_by_input_only_count"] += 1
        if args.solver == "c01":
            results = solve_graph_record_c01(graph_record, weights, max(1, args.top_k))
        elif args.solver == "c0_ctx":
            results = solve_graph_record_c0_ctx(
                graph_record, weights, max(1, args.top_k)
            )
        elif args.solver == "c0_ctx_rerank":
            results = solve_graph_record_c0_ctx_rerank(
                graph_record, weights, max(1, args.top_k)
            )
        elif args.solver == "c0_ctx_local":
            results = solve_graph_record_c0_ctx_local(
                graph_record, weights, max(1, args.top_k)
            )
        elif args.solver == "c0_ctx_local_top1":
            results = solve_graph_record_c0_ctx_local_top1(
                graph_record, weights, max(1, args.top_k)
            )
        elif args.solver == "c01_state_only":
            results = solve_graph_record_c01_state_only(
                graph_record, weights, max(1, args.top_k)
            )
        else:
            results = solve_graph_record(graph_record, weights, max(1, args.top_k))
        top_texts = [state.text for state in results[:3]]
        expected_text = str(reference.get("expected_text", ""))
        top1_text = top_texts[0] if top_texts else ""
        top1_hit = top1_text == expected_text
        top3_hit = expected_text in top_texts
        if top1_hit:
            top1_hits += 1
        if top3_hit:
            top3_hits += 1
        details.append(
            {
                "case_id": reference.get("case_id"),
                "input": reference.get("input"),
                "preceding_text": reference.get("preceding_text"),
                "expected_text": expected_text,
                "top1_text": top1_text,
                "top3_texts": top_texts,
                "top1_hit": top1_hit,
                "top3_hit": top3_hit,
                "match_strategy": match_strategy,
                "best_path_debug": results[0].debug_parts if results else [],
            }
        )

    evaluated = int(summary["evaluated_case_count"])
    summary["top1_hit_count"] = top1_hits
    summary["top3_hit_count"] = top3_hits
    if evaluated > 0:
        summary["top1_accuracy"] = top1_hits / evaluated
        summary["top3_accuracy"] = top3_hits / evaluated
    reference_case_count = int(summary["reference_case_count"])
    coverage_ratio = (evaluated / reference_case_count) if reference_case_count > 0 else 0.0
    summary["coverage_ratio"] = coverage_ratio
    warnings: list[str] = []
    graph_mtime = graph_path.stat().st_mtime
    reference_mtime = reference_path.stat().st_mtime
    if coverage_ratio < 0.95:
        warnings.append(
            f"Low graph coverage: evaluated {evaluated}/{reference_case_count} "
            f"({coverage_ratio:.3f})."
        )
    if graph_mtime > reference_mtime + 60:
        warnings.append(
            "Graph snapshot is newer than reference_cases; artifacts may come "
            "from different baseline runs."
        )
    elif reference_mtime > graph_mtime + 60:
        warnings.append(
            "Reference cases are newer than graph snapshot; artifacts may come "
            "from different baseline runs."
        )
    summary["warnings"] = warnings
    mismatches = [item for item in details if not item["top1_hit"]]
    write_json(output_json, {"summary": summary, "details": details})
    write_markdown(output_md, summary, mismatches)
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(f"JSON summary written to: {output_json}")
    print(f"Markdown summary written to: {output_md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
