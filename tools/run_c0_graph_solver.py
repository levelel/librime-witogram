@dataclass
class SolverWeights:
    dict_weight: float = 1.0
    vertex_risk_weight: float = 12.0
    edge_risk_weight: float = 24.0
    ambiguous_edge_penalty: float = 6.0
    single_char_penalty: float = 0.35
    multi_char_bonus: float = 0.18
    ctx_total_weight: float = 0.55
    ctx_avg_weight: float = 0.18
    ctx_oov_penalty: float = 0.65
    ctx_fallback_penalty: float = 0.45
    ctx_whole_word_bonus: float = 0.12
    ctx_rerank_scale: float = 0.15
    ctx_rerank_margin: float = 12.0
    ctx_local_scale: float = 0.10
    ctx_local_base_margin: float = 2.5
    ctx_local_gain_threshold: float = 0.30


@dataclass
class PathSegment:
    start: int
    end: int
    word: str
    dict_weight: float
    edge_risk: float
    edge_spelling_class: int
    vertex_risk: float
    is_rear: bool


@dataclass
class PathState:
    score: float
    text: str
    words: list[str]
    debug_parts: list[str]
    segments: list[PathSegment] = field(default_factory=list)
    context_suffix: str = ""
    last_word_len_class: int = 0
    trailing_single_char_run: int = 0
    recent_len_signature: str = ""


